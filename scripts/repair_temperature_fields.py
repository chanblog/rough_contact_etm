"""Repair corrupted saved temperature fields by recomputing them from heat_flux.

This is useful for results generated by earlier versions that wrote custom NumPy
fields through Tamaas H5Dumper.  The mechanical solution, current density, heat
flux, and scalar attributes are left unchanged.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import h5py
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from rough_contact_etm import config
from rough_contact_etm.thermal import solve_thermal_field


def valid_temperature(arr: np.ndarray) -> bool:
    return arr.size > 0 and np.all(np.isfinite(arr)) and float(np.nanmax(np.abs(arr))) < 1.0e12


def repair_file(path: pathlib.Path, force: bool = False) -> bool:
    with h5py.File(path, "r+") as h5:
        if "heat_flux" not in h5:
            print(f"skip: {path} (no heat_flux dataset)")
            return False
        if "temperature" in h5 and not force:
            old = np.asarray(h5["temperature"][:], dtype=float)
            if valid_temperature(old):
                print(f"ok:   {path}")
                return False
        heat_flux = np.asarray(h5["heat_flux"][:], dtype=float)
        temperature, _ = solve_thermal_field(heat_flux)
        if "temperature" in h5:
            del h5["temperature"]
        h5.create_dataset("temperature", data=temperature)
        print(f"fix:  {path}  Tmax={np.nanmax(temperature):.6g} K")
        return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--glob",
        default=str(pathlib.Path(config.hdf5_dump_dir) / "step_*_solution_0000.h5"),
        help="HDF5 field-data glob to repair. Default: %(default)s",
    )
    parser.add_argument("--force", action="store_true", help="Recompute even if the stored temperature field looks valid.")
    args = parser.parse_args()

    paths = sorted(pathlib.Path().glob(args.glob)) if not pathlib.Path(args.glob).is_absolute() else sorted(pathlib.Path("/").glob(args.glob.lstrip("/")))
    if not paths:
        print(f"No files matched: {args.glob}")
        return
    n_fixed = sum(repair_file(path, force=args.force) for path in paths)
    print(f"Done. Repaired {n_fixed} file(s).")


if __name__ == "__main__":
    main()
